export const GLYPH_W = 3;
export const GLYPH_H = 5;
export const CHAR_ADVANCE = 4;

/** Uppercase + strip accents so PT-BR text maps onto the ASCII font. */
export function normalizeText(s: string): string {
  return s.toUpperCase().normalize('NFD').replace(/[̀-ͯ]/g, '');
}

export function textWidth(s: string, scale = 1): number {
  const n = normalizeText(s).length;
  return n === 0 ? 0 : (n * CHAR_ADVANCE - 1) * scale;
}

export function drawText(ctx: CanvasRenderingContext2D, text: string, x: number, y: number, color: string, scale = 1): void {
  ctx.fillStyle = color;
  const s = normalizeText(text);
  let cx = Math.round(x);
  const cy = Math.round(y);
  for (const ch of s) {
    const g = GLYPHS[ch] ?? GLYPHS['?'];
    for (let r = 0; r < GLYPH_H; r++) {
      const row = g[r];
      for (let c = 0; c < GLYPH_W; c++) {
        if (row[c] === '1') ctx.fillRect(cx + c * scale, cy + r * scale, scale, scale);
      }
    }
    cx += CHAR_ADVANCE * scale;
  }
}

export function drawTextCentered(ctx: CanvasRenderingContext2D, text: string, cx: number, y: number, color: string, scale = 1): void {
  drawText(ctx, text, cx - textWidth(text, scale) / 2, y, color, scale);
}
