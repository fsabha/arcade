/** Mirror a map left-right (walls, creatures and the miner swap sides). */
function mirror(map: string[]): string[] {
  return map.map((row) => row.split('').reverse().join(''));
}

/** Levels 11-20 reuse the ten layouts mirrored, with extra vermin in the open air. */
function harden(map: string[], seed: number): string[] {
  const out = map.map((r) => r.split(''));
  let n = seed;
  const kinds = ['B', 'S', 'T'];
  for (let y = 2; y < out.length - 2; y++) {
    for (let x = 2; x < out[0].length - 2; x++) {
      n = (n * 1103515245 + 12345) & 0x7fffffff;
      if (out[y][x] !== '.' || n % 97 !== 0) continue;
      // only in open air, away from the start, the miner and other creatures
      let clear = true;
      for (let dy = -2; dy <= 2 && clear; dy++) for (let dx = -3; dx <= 3; dx++) {
        const c = out[y + dy]?.[x + dx];
        if (c === undefined || (c !== '.' && c !== '#')) { clear = false; break; }
      }
      if (clear) out[y][x] = kinds[n % 3];
    }
  }
  return out.map((r) => r.join(''));
}

/** Pads every row with rock to a whole number of screens (the hand-typed maps lose a border char here and there). */
function normalize(map: string[]): string[] {
  const w = Math.ceil(Math.max(...map.map((r) => r.length)) / 20) * 20;
  const rows = map.map((r) => r.padEnd(w, '#').slice(0, w));
  while (rows.length % 12 !== 0) rows.push('#'.repeat(w));
  return rows;
}

export function levelMap(level: number): string[] {
  const idx = ((level - 1) % 10);
  const base = normalize(BASE[idx]);
  const round = Math.floor((level - 1) / 10); // 0 = levels 1-10, 1 = 11-20, 2+ = PRO
  if (round === 0) return base;
  let m = round % 2 === 1 ? mirror(base) : base;
  for (let i = 0; i < round; i++) m = harden(m, level * 31 + i * 7);
  return m;
}

